"""32x32 hand-drawn ASCII sprites for the 12 Znome species.

Game Boy front-sprite style: black outline, white body, solid black masses
for identity, dither only for large shaded areas. Most bodies are symmetric,
so each species is drawn as a 16-column left half and mirrored.

'.' transparent, ' ' white, '#' black, '-' 25% dither, '+' 50% dither.
"""

from canvas import from_ascii

SIZE = 32

MIRROR = {"(": ")", ")": "(", "/": "\\", "\\": "/"}


def sym(half_rows):
    """Mirror a 16-char left half into full 32-char rows."""
    rows = []
    for r in half_rows:
        assert len(r) == 16, "half row must be 16 chars: %r (%d)" % (r, len(r))
        rows.append(r + "".join(MIRROR.get(c, c) for c in reversed(r)))
    assert len(rows) == SIZE, "need %d rows, got %d" % (SIZE, len(rows))
    return rows


