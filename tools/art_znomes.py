"""32x32 hand-drawn ASCII sprites for the 12 Znome species.

Game Boy front-sprite style: black outline, white body, solid black masses
for identity, dither only for large shaded areas. Templates are full-width
so poses can be asymmetric; `full` pads/validates rows.

'.' transparent, ' ' white, '#' black, '-' 25% dither, '+' 50% dither.
"""

from canvas import from_ascii

SIZE = 32


def full(rows):
    """Normalize a full-width template: pad/trim transparent right edge to 32."""
    assert len(rows) == SIZE, "need %d rows, got %d" % (SIZE, len(rows))
    out = []
    for r in rows:
        if len(r) < SIZE:
            r = r + "." * (SIZE - len(r))
        elif len(r) > SIZE:
            extra = r[SIZE:]
            assert set(extra) <= {"."}, "row overflows with art: %r" % r
            r = r[:SIZE]
        out.append(r)
    return out


